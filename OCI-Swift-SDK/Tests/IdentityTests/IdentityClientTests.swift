import XCTest
import Foundation
import OCICommon
@testable import identity

private struct StubSigner: Signer {
    func sign(_ req: inout URLRequest) throws { req.setValue("Signature stub", forHTTPHeaderField: "authorization") }
}

private final class Recorder: @unchecked Sendable {
    private let lock = NSLock()
    private var _reqs: [OCIRequest] = []
    var requests: [OCIRequest] { lock.lock(); defer { lock.unlock() }; return _reqs }
    func add(_ r: OCIRequest) { lock.lock(); _reqs.append(r); lock.unlock() }
}

private struct StubHTTP: HTTPClient {
    let recorder: Recorder
    let status: Int
    let headers: [String: String]
    let body: String
    func send(_ req: OCIRequest, host: String) async throws -> (Data, HTTPURLResponse) {
        recorder.add(req)
        let resp = HTTPURLResponse(url: URL(string: "https://\(host)\(req.path)")!, statusCode: status, httpVersion: "HTTP/1.1", headerFields: headers)!
        return (Data(body.utf8), resp)
    }
}

final class IdentityClientTests: XCTestCase {
    private func client(_ rec: Recorder, status: Int = 200, headers: [String: String] = [:], body: String) -> IdentityClient {
        IdentityClient(host: "identity.us-ashburn-1.oraclecloud.com", signer: StubSigner(),
                       http: StubHTTP(recorder: rec, status: status, headers: headers, body: body))
    }

    func testListUsersBuildsQueryAndDecodesItemsAndNextPage() async throws {
        let rec = Recorder()
        let json = #"[{"id":"ocid1.user.oc1..a","compartmentId":"ocid1.tenancy.oc1..t","name":"alice","lifecycleState":"ACTIVE","email":"a@example.com"}]"#
        let c = client(rec, headers: ["opc-next-page": "PAGE2", "opc-request-id": "req-1"], body: json)
        var req = ListUsersRequest()
        req.compartmentId = "ocid1.tenancy.oc1..t"
        req.limit = 5
        req.name = "alice"
        req.opcRequestId = "client-req"
        let resp = try await c.listUsers(req)
        let sent = try XCTUnwrap(rec.requests.first)
        XCTAssertEqual(sent.method, "GET")
        XCTAssertEqual(sent.path, "/20160918/users")
        XCTAssertEqual(sent.query["compartmentId"], "ocid1.tenancy.oc1..t")
        XCTAssertEqual(sent.query["limit"], "5")
        XCTAssertEqual(sent.query["name"], "alice")
        XCTAssertNil(sent.query["page"])
        XCTAssertEqual(sent.headers["opc-request-id"], "client-req")
        XCTAssertEqual(sent.headers["authorization"], "Signature stub")
        XCTAssertNil(sent.body)
        XCTAssertEqual(resp.items?.count, 1)
        XCTAssertEqual(resp.items![0].name, "alice")
        XCTAssertEqual(resp.items![0].email, "a@example.com")
        XCTAssertEqual(resp.opcNextPage, "PAGE2")
        XCTAssertEqual(resp.opcRequestId, "req-1")
    }

    func testGetUserSubstitutesPathParamAndReadsEtag() async throws {
        let rec = Recorder()
        let json = #"{"id":"ocid1.user.oc1..a","name":"bob","lifecycleState":"ACTIVE"}"#
        let c = client(rec, headers: ["etag": "abc123"], body: json)
        let resp = try await c.getUser(GetUserRequest(userId: "ocid1.user.oc1..a"))
        let sent = try XCTUnwrap(rec.requests.first)
        XCTAssertEqual(sent.method, "GET")
        XCTAssertEqual(sent.path, "/20160918/users/ocid1.user.oc1..a")
        XCTAssertTrue(sent.query.isEmpty)
        XCTAssertEqual(resp.etag, "abc123")
        XCTAssertEqual(resp.user?.name, "bob")
    }

    func testMissingPathParamThrowsBeforeNetwork() async {
        let rec = Recorder()
        let c = client(rec, body: "{}")
        do { _ = try await c.getUser(GetUserRequest()); XCTFail("expected throw") } catch {}
        XCTAssertTrue(rec.requests.isEmpty)
    }

    func testPostSendsRetryTokenFromRequestAndWorkRequestId() async throws {
        let rec = Recorder()
        let c = client(rec, status: 202, headers: ["opc-work-request-id": "wr-9"], body: "")
        let resp = try await c.activateDomain(ActivateDomainRequest(domainId: "d1", opcRetryToken: "tok-1"))
        let sent = try XCTUnwrap(rec.requests.first)
        XCTAssertEqual(sent.method, "POST")
        XCTAssertEqual(sent.path, "/20160918/domains/d1/actions/activate")
        XCTAssertEqual(sent.headers["opc-retry-token"], "tok-1")
        XCTAssertEqual(resp.opcWorkRequestId, "wr-9")
    }

    func testRetryTokenAutoGeneratedWhenAbsent() async throws {
        let rec = Recorder()
        let c = client(rec, status: 202, body: "")
        _ = try await c.activateDomain(ActivateDomainRequest(domainId: "d1"))
        let tok = try XCTUnwrap(rec.requests.first?.headers["opc-retry-token"])
        XCTAssertNotNil(UUID(uuidString: tok))
    }

    func testErrorResponseThrowsOCIError() async {
        let rec = Recorder()
        let c = client(rec, status: 404, body: #"{"code":"NotAuthorizedOrNotFound","message":"nope"}"#)
        do { _ = try await c.getUser(GetUserRequest(userId: "x")); XCTFail("expected throw") }
        catch let e as OCIError { XCTAssertEqual(e.statusCode, 404); XCTAssertEqual(e.code, "NotAuthorizedOrNotFound") }
        catch { XCTFail("wrong error \(error)") }
    }
}
